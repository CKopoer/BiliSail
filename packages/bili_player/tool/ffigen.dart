import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  final clang = Platform.environment['LIBCLANG_PATH'];
  await FfiGenerator(
    input: Input(entryPoints: [root.resolve('src/fvp_audio_activity.h')]),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = node.originalName.startsWith('bili_fvp_audio_');
          node.recordUse = true;
        },
      ),
    ],
    output: Output(
      dart: DartOutput(
        path: root.resolve('lib/src/third_party/fvp_audio_activity.g.dart'),
      ),
      recordUseMapping: root.resolve(
        'lib/src/third_party/fvp_audio_activity.record_use_mapping.g.dart',
      ),
      preamble:
          '// Copyright (c) 2026 BiliSail contributors. All rights reserved.\n'
          '// Generated by package:ffigen 23.0.0. Do not edit manually.\n'
          '// Regenerate: dart run tool/ffigen.dart\n',
    ),
  ).generate(libclangDylib: clang == null ? null : Uri.file(clang));
}
